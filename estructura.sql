CREATE DATABASE capstone_project;

DROP TABLE IF EXISTS pedidos;
DROP TABLE IF EXISTS productos;
DROP TABLE IF EXISTS clientes;

-- CLIENTES
CREATE TABLE clientes (
    id_cliente     INTEGER       PRIMARY KEY,
    nombre         VARCHAR(100)  NOT NULL,
    email          VARCHAR(150)  UNIQUE,
    ciudad         VARCHAR(80),                 
    fecha_registro DATE          NOT NULL
);

-- PRODUCTOS 
CREATE TABLE productos (
    id_producto  INTEGER        PRIMARY KEY,
    nombre       VARCHAR(100)   NOT NULL,
    categoria    VARCHAR(50)    NOT NULL,
    precio_lista NUMERIC(12,2)  NOT NULL CHECK (precio_lista > 0)  
);

--  PEDIDOS 
-- Cada fila es una línea de pedido: un cliente compra un producto.
CREATE TABLE pedidos (
    id_pedido       INTEGER        PRIMARY KEY,
    id_cliente      INTEGER        NOT NULL REFERENCES clientes(id_cliente),
    id_producto     INTEGER        NOT NULL REFERENCES productos(id_producto),
    fecha_pedido    DATE,
    cantidad        INTEGER        CHECK (cantidad > 0),
    precio_unitario NUMERIC(12,2)  CHECK (precio_unitario > 0)
);

CREATE INDEX idx_pedidos_cliente  ON pedidos(id_cliente);
CREATE INDEX idx_pedidos_producto ON pedidos(id_producto);

